import React, { useState } from 'react';
import { useApp } from '../../context/AppContext';
import { LeadRecord } from '../../types';
import {
  Users2,
  Download,
  Search,
  Filter,
  CheckCircle2,
  Clock,
  Calendar,
  ExternalLink,
  Building,
  Phone,
  Mail,
  Zap,
} from 'lucide-react';

export const LeadsCrmView: React.FC = () => {
  const { leads, currentTenant, showToast } = useApp();
  const [searchTerm, setSearchTerm] = useState('');
  const [selectedChannel, setSelectedChannel] = useState<string>('all');
  const [selectedLead, setSelectedLead] = useState<LeadRecord | null>(null);

  const filteredLeads = leads.filter((l) => {
    const matchesSearch =
      l.contactName.toLowerCase().includes(searchTerm.toLowerCase()) ||
      l.email.toLowerCase().includes(searchTerm.toLowerCase()) ||
      (l.qualificationDetails.budget &&
        l.qualificationDetails.budget.toLowerCase().includes(searchTerm.toLowerCase()));
    const matchesChannel =
      selectedChannel === 'all' || l.sourceChannel === selectedChannel;
    return matchesSearch && matchesChannel;
  });

  const handleExportCsv = () => {
    const csvContent =
      'data:text/csv;charset=utf-8,' +
      'Name,Email,Phone,Channel,Score,Budget,Timeframe,Appointment,CRM_Status\n' +
      leads
        .map(
          (l) =>
            `"${l.contactName}","${l.email}","${l.phone}","${l.sourceChannel}",${l.qualificationScore},"${l.qualificationDetails.budget || ''}","${l.qualificationDetails.timeframe || ''}","${l.appointmentTime || ''}","${l.crmSyncStatus}"`
        )
        .join('\n');
    const encodedUri = encodeURI(csvContent);
    const link = document.createElement('a');
    link.setAttribute('href', encodedUri);
    link.setAttribute('download', `agentgrid_leads_${currentTenant.slug}.csv`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    showToast(`Exported ${leads.length} leads to CSV`, 'success');
  };

  return (
    <div className="p-8 max-w-7xl mx-auto space-y-8 select-none">
      {/* Header */}
      <div className="flex flex-col md:flex-row md:items-center justify-between gap-4 pb-6 border-b border-slate-800">
        <div>
          <div className="flex items-center gap-2 text-xs font-mono text-indigo-400 mb-1">
            <span>MODULE: STRUCTURED CRM RECORDS &amp; DEALS</span>
            <span>·</span>
            <span>PIPELINE CONVERSION</span>
          </div>
          <h1 className="text-2xl font-bold tracking-tight text-white">
            Lead Qualification &amp; CRM Pipeline
          </h1>
          <p className="text-xs text-slate-400 mt-1">
            Autonomous qualification records generated by AI conversational agents, synced in real-time with HubSpot and Salesforce.
          </p>
        </div>

        <button
          onClick={handleExportCsv}
          className="px-4 py-2 rounded-xl text-xs font-semibold text-white bg-slate-900 border border-slate-700 hover:border-slate-600 transition-colors flex items-center gap-2 cursor-pointer self-start md:self-auto"
        >
          <Download className="w-4 h-4 text-cyan-400" />
          <span>Export Pipeline CSV</span>
        </button>
      </div>

      {/* Filter and Search Bar */}
      <div className="flex flex-col sm:flex-row items-center justify-between gap-3">
        <div className="relative w-full sm:w-80">
          <Search className="w-4 h-4 text-slate-500 absolute left-3 top-1/2 -translate-y-1/2" />
          <input
            type="text"
            value={searchTerm}
            onChange={(e) => setSearchTerm(e.target.value)}
            placeholder="Search by contact, budget, or criteria..."
            className="w-full pl-9 pr-4 py-2 bg-slate-900 border border-slate-800 rounded-xl text-xs text-white placeholder-slate-500 focus:outline-none focus:border-indigo-500 font-sans"
          />
        </div>

        {/* Channel Segment Filter */}
        <div className="flex items-center gap-1.5 p-1 bg-slate-900 border border-slate-800 rounded-xl text-xs self-start sm:self-auto">
          {['all', 'webchat', 'whatsapp', 'sms'].map((chan) => (
            <button
              key={chan}
              onClick={() => setSelectedChannel(chan)}
              className={`px-3 py-1 rounded-lg font-medium transition-colors capitalize cursor-pointer ${
                selectedChannel === chan
                  ? 'bg-indigo-600 text-white shadow-sm'
                  : 'text-slate-400 hover:text-white'
              }`}
            >
              {chan === 'all' ? 'All Channels' : chan}
            </button>
          ))}
        </div>
      </div>

      {/* Leads Table */}
      <div className="rounded-2xl border border-slate-800 bg-slate-900/60 overflow-hidden">
        <div className="overflow-x-auto">
          <table className="w-full text-left text-xs">
            <thead className="bg-slate-950/80 border-b border-slate-800 font-mono text-[11px] text-slate-400">
              <tr>
                <th className="py-3 px-4">Contact</th>
                <th className="py-3 px-4">Channel</th>
                <th className="py-3 px-4">Qualification Score</th>
                <th className="py-3 px-4">Budget &amp; Timeframe</th>
                <th className="py-3 px-4">Appointment</th>
                <th className="py-3 px-4">CRM Sync</th>
                <th className="py-3 px-4 text-right">Details</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-800/80">
              {filteredLeads.map((lead) => (
                <tr
                  key={lead.id}
                  className="hover:bg-slate-800/40 transition-colors cursor-pointer"
                  onClick={() => setSelectedLead(lead)}
                >
                  <td className="py-3.5 px-4">
                    <div className="font-bold text-white">{lead.contactName}</div>
                    <div className="text-[11px] text-slate-400 font-mono">
                      {lead.email} · {lead.phone}
                    </div>
                  </td>

                  <td className="py-3.5 px-4 font-mono text-[11px]">
                    <span className="capitalize text-slate-300 px-2 py-0.5 rounded bg-slate-950 border border-slate-800">
                      {lead.sourceChannel}
                    </span>
                  </td>

                  <td className="py-3.5 px-4 font-mono">
                    <div className="flex items-center gap-2">
                      <span
                        className={`font-bold tabular-nums ${
                          lead.qualificationScore >= 90
                            ? 'text-emerald-400'
                            : lead.qualificationScore >= 80
                            ? 'text-cyan-400'
                            : 'text-amber-400'
                        }`}
                      >
                        {lead.qualificationScore}/100
                      </span>
                      <span className="text-[10px] text-slate-500">
                        {lead.qualificationScore >= 90 ? 'VIP Ready' : 'Qualified'}
                      </span>
                    </div>
                  </td>

                  <td className="py-3.5 px-4">
                    <div className="text-white font-medium">
                      {lead.qualificationDetails.budget || 'In evaluation'}
                    </div>
                    <div className="text-[11px] text-slate-400 font-mono">
                      {lead.qualificationDetails.timeframe || '30-60 days'}
                    </div>
                  </td>

                  <td className="py-3.5 px-4 font-mono text-[11px]">
                    {lead.appointmentTime ? (
                      <span className="text-emerald-400 flex items-center gap-1">
                        <Calendar className="w-3.5 h-3.5 shrink-0" />
                        <span>{lead.appointmentTime}</span>
                      </span>
                    ) : (
                      <span className="text-slate-500">None locked</span>
                    )}
                  </td>

                  <td className="py-3.5 px-4 font-mono text-[11px]">
                    {lead.crmSyncStatus.startsWith('synced') ? (
                      <span className="text-emerald-400 font-medium">
                        ✓ {lead.crmSyncStatus.replace('_', ' ')}
                      </span>
                    ) : (
                      <span className="text-amber-400">pending sync</span>
                    )}
                  </td>

                  <td className="py-3.5 px-4 text-right">
                    <button
                      onClick={(e) => {
                        e.stopPropagation();
                        setSelectedLead(lead);
                      }}
                      className="px-2.5 py-1 rounded-lg bg-slate-800 hover:bg-slate-700 text-[11px] text-indigo-300 hover:text-white transition-colors"
                    >
                      Inspect
                    </button>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </div>

      {/* Selected Lead Modal Detail */}
      {selectedLead && (
        <div className="fixed inset-0 bg-slate-950/80 backdrop-blur-sm z-50 flex items-center justify-center p-4">
          <div className="w-full max-w-lg bg-slate-900 border border-slate-700 rounded-2xl p-6 shadow-2xl space-y-4">
            <div className="flex items-center justify-between border-b border-slate-800 pb-3">
              <div>
                <h3 className="text-base font-bold text-white">{selectedLead.contactName}</h3>
                <p className="text-xs text-slate-400 font-mono">
                  Captured via {selectedLead.sourceChannel} · {selectedLead.createdAt}
                </p>
              </div>
              <button
                onClick={() => setSelectedLead(null)}
                className="text-slate-400 hover:text-white"
              >
                ✕
              </button>
            </div>

            <div className="space-y-3 text-xs">
              <div className="grid grid-cols-2 gap-3 font-mono text-[11px]">
                <div className="p-3 rounded-xl bg-slate-950 border border-slate-800">
                  <span className="text-slate-500 block uppercase">Qualification Score</span>
                  <span className="text-emerald-400 font-bold text-sm">
                    {selectedLead.qualificationScore} / 100
                  </span>
                </div>
                <div className="p-3 rounded-xl bg-slate-950 border border-slate-800">
                  <span className="text-slate-500 block uppercase">CRM Status</span>
                  <span className="text-cyan-300 font-semibold">{selectedLead.crmSyncStatus}</span>
                </div>
              </div>

              <div className="p-3.5 rounded-xl bg-slate-950 border border-slate-800 space-y-1.5">
                <span className="text-slate-400 font-mono text-[11px] block">Extracted Criteria:</span>
                <div className="text-white">
                  <strong>Budget:</strong> {selectedLead.qualificationDetails.budget}
                </div>
                <div className="text-white">
                  <strong>Timeframe:</strong> {selectedLead.qualificationDetails.timeframe}
                </div>
                <div className="text-white">
                  <strong>Property / Interest:</strong> {selectedLead.qualificationDetails.propertyType || selectedLead.qualificationDetails.interest}
                </div>
              </div>

              <div className="p-3 rounded-xl bg-slate-950 border border-slate-800">
                <span className="text-slate-400 font-mono text-[11px] block mb-1">
                  Conversation Excerpt:
                </span>
                <p className="text-slate-300 italic text-[11px]">
                  &ldquo;{selectedLead.conversationSnippet}&rdquo;
                </p>
              </div>
            </div>

            <div className="pt-2 flex justify-end">
              <button
                onClick={() => setSelectedLead(null)}
                className="px-4 py-2 bg-indigo-600 hover:bg-indigo-500 text-white rounded-xl text-xs font-semibold"
              >
                Close Inspector
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
